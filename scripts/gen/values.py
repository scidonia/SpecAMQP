DESCRIPTOR_SYMBOL = {"type": "symbol", "text": "amqp:example"}
DESCRIPTOR_ULONG = {"type": "ulong", "value": 0x00000000_00000001}


def golden() -> list[dict]:
    vectors: list[dict] = []

    def add(name: str, value: dict, anchor: str | list[str], note: str) -> None:
        clauses = [anchor] if isinstance(anchor, str) else list(anchor)
        vectors.append({
            "vector": f"gen-{name}", "kind": "encode", "clauses": clauses,
            "bytes": encode(value).hex(), "value": value, "note": note,
        })
        vectors.append({
            "vector": f"gen-{name}-decode", "kind": "decode", "clauses": clauses,
            "bytes": encode(value).hex(), "value": value, "canonical": True,
            "note": f"{note} (decoding direction)",
        })

    # Scalar boundaries. Every width is exercised on both sides of each boundary,
    # because that is where a narrowest-encoding rule and a size field disagree.
    for label, values, anchor in (
        ("ubyte", [0, 1, 127, 128, 255], WIDTHS_ANCHOR),
        ("byte", [-128, -1, 0, 1, 127], WIDTHS_ANCHOR),
        ("ushort", [0, 1, 255, 256, 32767, 65535], WIDTHS_ANCHOR),
        ("short", [-32768, -1, 0, 32767], WIDTHS_ANCHOR),
        ("uint", [0, 1, 254, 255, 256, 65535, 65536, 2**31 - 1, 2**32 - 1], WIDTHS_ANCHOR),
        ("int", [-(2**31), -1, 0, 2**31 - 1], WIDTHS_ANCHOR),
        ("ulong", [0, 1, 255, 256, 2**32 - 1, 2**32, 2**63, 2**64 - 1], WIDTHS_ANCHOR),
        ("long", [-(2**63), -1, 0, 2**63 - 1], WIDTHS_ANCHOR),
    ):
        for value in values:
            add(f"{label}-{value}", {"type": label, "value": value}, anchor,
                f"{label} value {value}, encoded in the narrowest form that carries it")

    add("null", {"type": "null"}, DESCRIBED_ANCHOR, "the null value")
    add("boolean-true", {"type": "boolean", "value": True}, WIDTHS_ANCHOR, "true")
    add("boolean-false", {"type": "boolean", "value": False}, WIDTHS_ANCHOR, "false")

    # Variable-width payloads: the 8-to-32-bit length boundary is where a writer
    # must switch form and a reader must not.
    for label, length in (("empty", 0), ("one", 1), ("short", 254), ("max8", 255),
                          ("over8", 256), ("large", 70000)):
        text = "x" * length
        add(f"string-{label}", {"type": "string", "text": text}, STRING_ANCHOR,
            f"a string of {length} octets")
        add(f"symbol-{label}", {"type": "symbol", "text": text}, STRING_ANCHOR,
            f"a symbol of {length} octets")
        add(f"binary-{label}", {"type": "binary", "hex": ("ab" * length)},
            STRING_ANCHOR, f"binary data of {length} octets")

    # Compounds: counts at the 8-bit boundary, sizes across it, nesting.
    for count in (0, 1, 2, 254, 255, 256, 300):
        items = [{"type": "ubyte", "value": i % 256} for i in range(count)]
        add(f"list-{count}", {"type": "list", "items": items}, COMPOUND_ANCHOR,
            f"a list of {count} booleans")
    for count in (0, 1, 2, 255, 256):
        items = [{"type": "string", "text": "e" * 40} for _ in range(count)]
        add(f"array-strings-{count}",
            {"type": "array", "constructor": "a1", "items": items}, ARRAY_ANCHOR,
            f"an array of {count} strings")
    add("array-null", {"type": "array", "constructor": "40",
                       "items": [{"type": "null"}, {"type": "null"}]}, ARRAY_ANCHOR,
        "an array of nulls, whose elements carry no data at all")

    # Zero-width element constructors: elements that carry no octets of their own, so
    # the buffer is smaller than the element count. Part 1 bounds the count by the
    # count field and by nothing in the data, so every one of these is a legal encoding
    # up to the declared element limit — in whichever form the count's width selects,
    # eight-bit up to 255 elements and thirty-two-bit beyond — and a reader must
    # materialise them rather than report truncation.
    for constructor, element in (("40", {"type": "null"}),
                                 ("41", {"type": "boolean", "value": True}),
                                 ("42", {"type": "boolean", "value": False})):
        for count in (0, 1, 2, 255, 256, 257):
            add(f"zero-width-{constructor}-{count}",
                {"type": "array", "constructor": constructor,
                 "items": [dict(element) for _ in range(count)]},
                ENCODINGS_CLAUSE,
                f"{count} zero-width {constructor} element(s) occupying no element data")
    add("list-nested",
        {"type": "list", "items": [
            {"type": "list", "items": [{"type": "uint", "value": 7}]},
            {"type": "array", "constructor": "70",
             "items": [{"type": "uint", "value": 1}, {"type": "uint", "value": 2}]},
            {"type": "described", "descriptor": DESCRIPTOR_SYMBOL, "value": {"type": "null"}},
        ]}, COMPOUND_ANCHOR, "a list containing a list, an array and a described value")
    add("described-symbol", {"type": "described", "descriptor": DESCRIPTOR_SYMBOL,
                             "value": {"type": "string", "text": "payload"}},
        DESCRIBED_ANCHOR, "a described value with a symbolic descriptor")
    add("described-numeric", {"type": "described", "descriptor": DESCRIPTOR_ULONG,
                              "value": {"type": "list", "items": []}},
        DESCRIBED_ANCHOR, "a described value with a numeric descriptor, wrapping the empty list")

    # The remaining fixed-width encodings. What the artifact's table fixes for
    # these is the framing — a format code and a declared number of octets — so the
    # float, double and decimal payloads are carried as raw hex rather than as JSON
    # numbers, which could not pin the octets a vector exists to pin down.
    for codepoint in (0, 65, 0x10FFFF):
        add(f"char-{codepoint:06x}", {"type": "char", "codepoint": codepoint},
            FIXED_ANCHOR,
            f"the code point U+{codepoint:04X}, UTF-32BE in four octets")
    for milliseconds in (0, 1, -(2**63), 2**63 - 1):
        add(f"timestamp-{milliseconds}", {"type": "timestamp", "milliseconds": milliseconds},
            FIXED_ANCHOR,
            f"{milliseconds} milliseconds since the Unix epoch, two's complement in eight octets")
    for label, payload in (("zero", "00" * 16),
                           ("rfc4122", "f81d4fae7dec11d0a76500a0c91e6bf6")):
        add(f"uuid-{label}", {"type": "uuid", "hex": payload}, FIXED_ANCHOR,
            f"a UUID in sixteen octets, the {label} pattern")
    for label, payload in (("positive-zero", "00000000"),
                           ("negative-zero", "80000000"),
                           ("one", "3f800000"),
                           ("min-subnormal", "00000001"),
                           ("max-finite", "7f7fffff"),
                           ("positive-infinity", "7f800000"),
                           ("negative-infinity", "ff800000")):
        add(f"float-{label}", {"type": "float", "hex": payload}, FIXED_ANCHOR,
            f"binary32 {label}: the sign, exponent and mantissa extremes in four octets")
    for label, payload in (("positive-zero", "0000000000000000"),
                           ("negative-zero", "8000000000000000"),
                           ("one", "3ff0000000000000"),
                           ("min-subnormal", "0000000000000001"),
                           ("max-finite", "7fefffffffffffff"),
                           ("positive-infinity", "7ff0000000000000"),
                           ("negative-infinity", "fff0000000000000")):
        add(f"double-{label}", {"type": "double", "hex": payload}, FIXED_ANCHOR,
            f"binary64 {label}: the sign, exponent and mantissa extremes in eight octets")
    for decimal, width in (("decimal32", 4), ("decimal64", 8), ("decimal128", 16)):
        for label, payload in (("zero", "00" * width), ("all-ones", "ff" * width)):
            add(f"{decimal}-{label}", {"type": decimal, "hex": payload}, FIXED_ANCHOR,
                f"{decimal} {label}: Binary Integer Decimal in {width} octets, carried as raw hex")

    # Maps. The count field is the number of items — two per pair — and there is no
    # map0 form, so the empty map is map8 with a zero item count. Keys are symbolic
    # and values mixed, and the pairs are given in wire order because Part 1 makes
    # that order semantically significant.
    def pair(index: int) -> list[dict]:
        values = ({"type": "null"}, {"type": "boolean", "value": True},
                  {"type": "ubyte", "value": index % 256},
                  {"type": "string", "text": f"v{index}"},
                  {"type": "uint", "value": index})
        return [{"type": "symbol", "text": f"k{index}"}, values[index % len(values)]]

    add("map-0", {"type": "map", "pairs": []}, MAP_CLAUSE,
        "the empty map: no map0 form exists, so map8 with a zero item count")
    add("map-1", {"type": "map", "pairs": [pair(0)]}, MAP_CLAUSE,
        "one symbolic key mapped to a null value, in wire order")
    for count in (127, 128, 255, 256):
        pairs = [pair(i) for i in range(count)]
        value = {"type": "map", "pairs": pairs}
        octets = encode(value)
        body = sum(len(encode(key)) + len(encode(item)) for key, item in pairs)
        add(f"map-{count}", value, MAP_CLAUSE,
            f"a map of {count} pairs, {2 * count} items in {len(octets)} octets: the item "
            f"count {'fits' if 2 * count <= 0xFF else 'does not fit'} the one-octet count "
            f"field and the body {'fits' if 1 + body <= 0xFF else 'does not fit'} the "
            f"one-octet size field, so {'map8' if octets[0] == 0xC1 else 'map32'} carries it")
    add("map-nested", {"type": "map", "pairs": [
        [{"type": "symbol", "text": "outer"},
         {"type": "map", "pairs": [[{"type": "symbol", "text": "inner"},
                                    {"type": "uint", "value": 7}]]}],
        [{"type": "symbol", "text": "tail"}, {"type": "null"}],
    ]}, MAP_CLAUSE, "a map with a map as one of its values")
    return vectors


def rejects(golden_vectors: list[dict]) -> list[dict]:
    vectors: list[dict] = []

    # Every octet below the format-code ranges, and the twelve escape octets.
    for code in range(0x01, 0x40):
        vectors.append({
            "vector": f"gen-reserved-{code:02x}", "kind": "reject",
            "clauses": [WIDTHS_ANCHOR], "bytes": f"{code:02x}",
            "expectError": {"condition": "amqp:decode-error", "endpoint": "connection"},
            "note": f"0x{code:02X} lies below every format-code range",
        })
    for code in (0x4F, 0x5F, 0x6F, 0x7F, 0x8F, 0x9F, 0xAF, 0xBF, 0xCF, 0xDF, 0xEF, 0xFF):
        vectors.append({
            "vector": f"gen-escape-{code:02x}", "kind": "reject",
            "clauses": ["amqp-core-types-v1.0-os.xml#picture.3"], "bytes": f"{code:02x}00",
            "expectError": {"condition": "amqp:decode-error", "endpoint": "connection"},
            "note": f"0x{code:02X} is an escape octet reserved for future formats",
        })

    # Part 1: a map's items are alternating keys and values, so the count must be
    # even. The size field here is exactly right, leaving the parity the only
    # thing wrong with the input.
    odd = b"".join(encode(item) for item in (
        {"type": "symbol", "text": "a"}, {"type": "uint", "value": 0}, {"type": "null"}))
    vectors.append({
        "vector": "gen-map-odd-items", "kind": "reject", "clauses": [MAP_CLAUSE],
        "bytes": (bytes([0xC1, 1 + len(odd), 3]) + odd).hex(),
        "expectError": {"condition": "amqp:decode-error", "endpoint": "connection"},
        "note": "a map declaring three items: keys and values must come in pairs, "
                "so an odd item count is not a map",
    })

    # The declared element limit on the zero-width family, and its size control. A ten
    # octet buffer can declare billions of elements, so what bounds an array of them is
    # the declared limit — named, so that it is never mistaken for truncation — and the
    # size field is still checked where it lies.
    vectors.append({
        "vector": "gen-zero-width-40-over-limit", "kind": "reject",
        "clauses": [ENCODINGS_CLAUSE],
        "bytes": (bytes([0xF0]) + be(5, 4) + be(65537, 4) + bytes([0x40])).hex(),
        "expectError": {"condition": "amqp:decode-error", "endpoint": "connection",
                        "reason": "limit"},
        "note": "65537 zero-width elements: refused by the declared element limit, not "
                "by truncation, because a count is not an octet count",
    })
    vectors.append({
        "vector": "gen-zero-width-40-bad-size", "kind": "reject",
        "clauses": [ENCODINGS_CLAUSE],
        "bytes": (bytes([0xE0, 0x03, 0x0A, 0x40])).hex(),
        "expectError": {"condition": "amqp:decode-error", "endpoint": "connection",
                        "reason": "sizeMismatch"},
        "note": "ten zero-width elements with the size field raised by one: the reading "
                "measures two octets where three are declared, which is a size mismatch "
                "rather than a limit",
    })

    # Every proper prefix of every golden encoding must be rejected as truncated.
    for entry in golden_vectors:
        octets = bytes.fromhex(entry["bytes"])
        if len(octets) < 2 or len(octets) > 40:
            continue                      # keep the sweep to short vectors
        for cut in range(1, len(octets)):
            vectors.append({
                "vector": f"trunc-{entry['vector']}-{cut}", "kind": "reject",
                "clauses": entry["clauses"],
                "bytes": octets[:cut].hex(),
                "expectError": {"condition": "amqp:decode-error", "endpoint": "connection"},
                "note": f"the first {cut} of {len(octets)} octets of {entry['vector']}",
            })

    # Size fields perturbed by one octet, for the compound encodings. A reader that
    # trusts the declared size instead of measuring its own window accepts a map
    # whose size field is short, so this is the control that makes the check bite.
    for entry in golden_vectors:
        octets = bytearray.fromhex(entry["bytes"])
        value = entry.get("value", {})
        if value.get("type") not in ("list", "map") or len(octets) < 3:
            continue
        if octets[0] not in (0xC0, 0xD0, 0xC1, 0xD1):
            continue
        for delta in (-1, 1):
            # The vector id must satisfy the schema's `^[a-z0-9][a-z0-9._-]*$`, so
            # the sign is spelled out rather than written as `+`/`-`.
            direction = "minus1" if delta < 0 else "plus1"
            if octets[0] in (0xC0, 0xC1):
                perturbed = bytearray(octets)
                perturbed[1] = (perturbed[1] + delta) % 256
            else:
                size = int.from_bytes(octets[1:5], "big") + delta
                perturbed = bytearray(octets[:1]) + size.to_bytes(4, "big") + octets[5:]
            vectors.append({
                "vector": f"size-{direction}-{entry['vector']}", "kind": "reject",
                "clauses": entry["clauses"], "bytes": bytes(perturbed).hex(),
                "expectError": {"condition": "amqp:decode-error", "endpoint": "connection"},
                "note": f"{entry['vector']} with its size field moved by {delta}",
            })
    return vectors


def properties() -> list[dict]:
    """Exhaustive short inputs, asserting a law that needs no oracle.

    If a byte string decodes to a value, encoding that value must decode to the
    same value. Inputs that fail to decode make no claim, so the whole space of
    one- and two-octet inputs can be swept without an expected answer for each.
    """
    vectors: list[dict] = []
    for first in range(256):
        vectors.append({
            "vector": f"prop-{first:02x}", "kind": "property",
            "property": "decode-stable", "clauses": [WIDTHS_ANCHOR],
            "bytes": f"{first:02x}",
        })
    for first in range(256):
        for second in range(256):
            vectors.append({
                "vector": f"prop-{first:02x}{second:02x}", "kind": "property",
                "property": "decode-stable", "clauses": [WIDTHS_ANCHOR],
                "bytes": f"{first:02x}{second:02x}",
            })
    return vectors


