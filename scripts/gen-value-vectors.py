# ---------------------------------------------------------------- the encoder


def be(n: int, width: int) -> bytes:
    return n.to_bytes(width, "big")


def enc_uint(n: int) -> bytes:
    if n == 0:
        return bytes([0x43])
    if n <= 0xFF:
        return bytes([0x52, n])
    if n <= 0xFFFFFFFF:
        return bytes([0x70]) + be(n, 4)
    raise ValueError("uint out of range")


def enc_ulong(n: int) -> bytes:
    if n == 0:
        return bytes([0x44])
    if n <= 0xFF:
        return bytes([0x53, n])
    if n <= 0xFFFFFFFFFFFFFFFF:
        return bytes([0x80]) + be(n, 8)
    raise ValueError("ulong out of range")


def enc_int(n: int) -> bytes:
    if -(2**31) <= n < 2**31:
        return bytes([0x71]) + be(n % 2**32, 4)
    raise ValueError("int out of range")


def enc_long(n: int) -> bytes:
    if -(2**63) <= n < 2**63:
        return bytes([0x81]) + be(n % 2**64, 8)
    raise ValueError("long out of range")


def enc_variable(narrow: int, wide: int, payload: bytes) -> bytes:
    if len(payload) <= 0xFF:
        return bytes([narrow, len(payload)]) + payload
    return bytes([wide]) + be(len(payload), 4) + payload


def fixed(label: str, payload_hex: str, width: int) -> bytes:
    """A fixed-width payload given as hex, checked against the declared width.

    The artifact's encoding table fixes how many octets each of the fixed-width
    encodings carries; a payload of the wrong length is a malformed vector, not a
    value, so it is refused here rather than written into the corpus.
    """
    payload = bytes.fromhex(payload_hex)
    if len(payload) != width:
        raise ValueError(f"{label} payload is {len(payload)} octets, the table declares {width}")
    return payload


def encode(value: dict) -> bytes:
    kind = value["type"]
    if kind == "null":
        return bytes([0x40])
    if kind == "boolean":
        return bytes([0x41 if value["value"] else 0x42])
    if kind == "ubyte":
        return bytes([0x50, value["value"]])
    if kind == "byte":
        return bytes([0x51, value["value"] % 256])
    if kind == "ushort":
        return bytes([0x60]) + be(value["value"], 2)
    if kind == "short":
        return bytes([0x61]) + be(value["value"] % 2**16, 2)
    if kind == "uint":
        return enc_uint(value["value"])
    if kind == "int":
        return enc_int(value["value"])
    if kind == "ulong":
        return enc_ulong(value["value"])
    if kind == "long":
        return enc_long(value["value"])
    if kind == "float":
        return bytes([0x72]) + fixed("float", value["hex"], 4)
    if kind == "double":
        return bytes([0x82]) + fixed("double", value["hex"], 8)
    if kind == "decimal32":
        return bytes([0x74]) + fixed("decimal32", value["hex"], 4)
    if kind == "decimal64":
        return bytes([0x84]) + fixed("decimal64", value["hex"], 8)
    if kind == "decimal128":
        return bytes([0x94]) + fixed("decimal128", value["hex"], 16)
    if kind == "char":
        codepoint = value["codepoint"]
        if not 0 <= codepoint <= 0x10FFFF:
            raise ValueError("char code point out of range")
        return bytes([0x73]) + be(codepoint, 4)
    if kind == "timestamp":
        # Two's complement milliseconds since the Unix epoch: a time before the
        # epoch is a wrapped octet string, not an error.
        return bytes([0x83]) + be(value["milliseconds"] % 2**64, 8)
    if kind == "uuid":
        return bytes([0x98]) + fixed("uuid", value["hex"], 16)
    if kind == "string":
        return enc_variable(0xA1, 0xB1, value["text"].encode())
    if kind == "symbol":
        return enc_variable(0xA3, 0xB3, value["text"].encode())
    if kind == "binary":
        return enc_variable(0xA0, 0xB0, bytes.fromhex(value["hex"]))
    if kind == "described":
        return bytes([0x00]) + encode(value["descriptor"]) + encode(value["value"])
    if kind == "list":
        body = b"".join(encode(item) for item in value["items"])
        if not value["items"]:
            return bytes([0x45])
        count = len(value["items"])
        # The size counts the octets after it: the count field (whose width
        # depends on the form) then the items.
        if 1 + len(body) <= 0xFF and count <= 0xFF:
            return bytes([0xC0, 1 + len(body), count]) + body
        return bytes([0xD0]) + be(4 + len(body), 4) + be(count, 4) + body
    if kind == "map":
        # Like list, but the count is the number of *items* — two per key/value
        # pair — and there is no map0 form, so the empty map is map8 with a zero
        # count. Part 1 requires an even item count; an odd one is not a map.
        pairs = value["pairs"]
        body = b"".join(encode(key) + encode(item) for key, item in pairs)
        count = 2 * len(pairs)
        if 1 + len(body) <= 0xFF and count <= 0xFF:
            return bytes([0xC1, 1 + len(body), count]) + body
        return bytes([0xD1]) + be(4 + len(body), 4) + be(count, 4) + body
    if kind == "array":
        ctor = int(value["constructor"], 16)
        elements = b"".join(element_data(ctor, item) for item in value["items"])
        count = len(value["items"])
        if 2 + len(elements) <= 0xFF and count <= 0xFF:
            return bytes([0xE0, 2 + len(elements), count, ctor]) + elements
        return (bytes([0xF0]) + be(5 + len(elements), 4) + be(count, 4)
                + bytes([ctor]) + elements)
    raise ValueError(f"unknown value type {kind!r}")


def compound_element_data(width: int, kind: str, count: int, body: bytes) -> bytes:
    """A compound element's data: the size and count fields the array's constructor
    fixes, then the body. A count or size the declared width cannot announce is a
    malformed vector, not a value, so it is refused here rather than written short."""
    size = width + len(body)
    if size >= 2 ** (8 * width) or count >= 2 ** (8 * width):
        raise ValueError(f"a {kind} element of width {width} cannot announce "
                         f"{count} item(s) in {len(body)} octet(s)")
    return be(size, width) + be(count, width) + body


def array_element_data(width: int, constructor: int, items: list[dict]) -> bytes:
    """An array element's data where the array's own element constructor is an array:
    its size and count in the outer array's declared width, its element constructor,
    then its elements. The inner array has no narrowest form of its own here — the
    outer constructor fixes it — which is what makes the forced width testable."""
    body = b"".join(element_data(constructor, item) for item in items)
    size = width + 1 + len(body)
    if size >= 2 ** (8 * width) or len(items) >= 2 ** (8 * width):
        raise ValueError(f"an array element of width {width} cannot announce "
                         f"{len(items)} element(s) in {len(body)} octet(s)")
    return be(size, width) + be(len(items), width) + bytes([constructor]) + body


def element_data(constructor: int, value: dict) -> bytes:
    """Array element data, in the array's declared constructor form.

    The array states its element constructor once, so each element's data is in that
    form and only that form: the width of a size, count or length field is the array's
    constructor's choice, never the element's own preference. Every constructor the
    table assigns is written here explicitly — there is no fallback to the element's own
    encoding, which would write a form the array does not declare — and a value the
    declared form cannot carry is refused rather than written in another form.
    """
    kind = value["type"]
    if constructor == 0x00:
        if kind != "described":
            raise ValueError(f"the descriptor prefix carries described values, not {kind}")
        return encode(value["descriptor"]) + encode(value["value"])
    if constructor in (0x40, 0x41, 0x42):
        return b""
    if constructor == 0x43:
        if kind != "uint" or value["value"] != 0:
            raise ValueError("a uint0 element carries the value 0")
        return b""
    if constructor == 0x44:
        if kind != "ulong" or value["value"] != 0:
            raise ValueError("a ulong0 element carries the value 0")
        return b""
    if constructor == 0x45:
        if kind != "list" or value["items"]:
            raise ValueError("a list0 element carries the empty list")
        return b""
    if constructor == 0x50:
        _expect(kind, "ubyte")
        return bytes([value["value"]])
    if constructor == 0x51:
        _expect(kind, "byte")
        return be(value["value"] % 2**8, 1)
    if constructor == 0x52:
        _expect(kind, "uint")
        return _octet(value["value"], 0xFF, "smalluint")
    if constructor == 0x53:
        _expect(kind, "ulong")
        return _octet(value["value"], 0xFF, "smallulong")
    if constructor == 0x54:
        _expect(kind, "int")
        return _signed_octet(value["value"], "smallint")
    if constructor == 0x55:
        _expect(kind, "long")
        return _signed_octet(value["value"], "smalllong")
    if constructor == 0x56:
        _expect(kind, "boolean")
        return bytes([1 if value["value"] else 0])
    if constructor == 0x60:
        _expect(kind, "ushort")
        return be(value["value"], 2)
    if constructor == 0x61:
        _expect(kind, "short")
        return be(value["value"] % 2**16, 2)
    if constructor == 0x70:
        _expect(kind, "uint")
        return be(value["value"], 4)
    if constructor == 0x71:
        _expect(kind, "int")
        return be(value["value"] % 2**32, 4)
    if constructor == 0x72:
        return fixed("float", value["hex"], 4)
    if constructor == 0x73:
        _expect(kind, "char")
        return be(value["codepoint"], 4)
    if constructor == 0x74:
        return fixed("decimal32", value["hex"], 4)
    if constructor == 0x80:
        _expect(kind, "ulong")
        return be(value["value"], 8)
    if constructor == 0x81:
        _expect(kind, "long")
        return be(value["value"] % 2**64, 8)
    if constructor == 0x82:
        return fixed("double", value["hex"], 8)
    if constructor == 0x83:
        _expect(kind, "timestamp")
        return be(value["milliseconds"] % 2**64, 8)
    if constructor == 0x84:
        return fixed("decimal64", value["hex"], 8)
    if constructor == 0x94:
        return fixed("decimal128", value["hex"], 16)
    if constructor == 0x98:
        return fixed("uuid", value["hex"], 16)
    if constructor == 0xA0:
        _expect(kind, "binary")
        return _length_prefixed(1, "vbin8", bytes.fromhex(value["hex"]))
    if constructor == 0xA1:
        _expect(kind, "string")
        return _length_prefixed(1, "str8", value["text"].encode())
    if constructor == 0xA3:
        _expect(kind, "symbol")
        return _length_prefixed(1, "sym8", value["text"].encode())
    if constructor == 0xB0:
        _expect(kind, "binary")
        return _length_prefixed(4, "vbin32", bytes.fromhex(value["hex"]))
    if constructor == 0xB1:
        _expect(kind, "string")
        return _length_prefixed(4, "str32", value["text"].encode())
    if constructor == 0xB3:
        _expect(kind, "symbol")
        return _length_prefixed(4, "sym32", value["text"].encode())
    if constructor in (0xC0, 0xD0):
        _expect(kind, "list")
        body = b"".join(encode(item) for item in value["items"])
        return compound_element_data(1 if constructor == 0xC0 else 4, "list",
                                     len(value["items"]), body)
    if constructor in (0xC1, 0xD1):
        _expect(kind, "map")
        body = b"".join(encode(key) + encode(item) for key, item in value["pairs"])
        return compound_element_data(1 if constructor == 0xC1 else 4, "map",
                                     2 * len(value["pairs"]), body)
    if constructor in (0xE0, 0xF0):
        _expect(kind, "array")
        inner = int(value["constructor"], 16)
        return array_element_data(1 if constructor == 0xE0 else 4, inner, value["items"])
    raise ValueError(f"element constructor {constructor:#04x} is not one the corpus writes")


def _expect(kind: str, wanted: str) -> None:
    if kind != wanted:
        raise ValueError(f"an element of this form carries {wanted} values, not {kind}")


def _octet(n: int, bound: int, label: str) -> bytes:
    if not 0 <= n <= bound:
        raise ValueError(f"a {label} element carries one octet and {n} does not fit")
    return bytes([n])


def _signed_octet(n: int, label: str) -> bytes:
    if not -128 <= n <= 127:
        raise ValueError(f"a {label} element carries one signed octet and {n} does not fit")
    return bytes([n % 2**8])


def _length_prefixed(width: int, label: str, payload: bytes) -> bytes:
    if len(payload) >= 2 ** (8 * width):
        raise ValueError(f"a {label} element carries {len(payload)} octet(s), which a "
                         f"{width}-octet length field cannot announce")
    return be(len(payload), width) + payload


# ------------------------------------------------- the artifact's own examples


def artifact_examples() -> list[tuple[str, dict, bytes]]:
    """The worked examples Part 1 publishes, as (name, value, octets)."""
    hello = "Hello Glorious Messaging World"
    url = "http://example.org/hello-world"
    title = "AMQP for & by Dummies"
    a1 = "Rob J. Godfrey"
    a2 = "Rafael H. Schloming"
    book = "example:book:list"
    book_value = {
        "type": "described",
        "descriptor": {"type": "symbol", "text": book},
        "value": {
            "type": "list",
            "items": [
                {"type": "string", "text": title},
                {"type": "array", "constructor": "a1",
                 "items": [{"type": "string", "text": a1}, {"type": "string", "text": a2}]},
                {"type": "null"},
            ],
        },
    }
    return [
        ("str8-hello", {"type": "string", "text": hello},
         bytes([0xA1, 0x1E]) + hello.encode()),
        ("described-url", {"type": "described", "descriptor": {"type": "string", "text": "URL"},
                           "value": {"type": "string", "text": url}},
         bytes([0x00, 0xA1, 0x03]) + b"URL" + bytes([0xA1, 0x1E]) + url.encode()),
        ("book-composite", book_value, bytes.fromhex(
            "00" "a311" + book.encode().hex() + "c04003" + "a115" + title.encode().hex()
            + "e02502" + "a10e" + a1.encode().hex() + "13" + a2.encode().hex() + "40")),
    ]


def self_check() -> None:
    """The generator must reproduce the artifact's examples, or it is not trusted."""
    for name, value, expected in artifact_examples():
        produced = encode(value)
        if produced != expected:
            raise SystemExit(
                f"gen-value-vectors: the encoder disagrees with the artifact's {name} example\n"
                f"  artifact: {expected.hex()}\n  produced: {produced.hex()}"
            )


